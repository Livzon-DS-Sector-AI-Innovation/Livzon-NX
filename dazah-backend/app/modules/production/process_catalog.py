def _label(name: str) -> str:
    if name in _LABEL_OVERRIDES:
        return _LABEL_OVERRIDES[name]
    return "".join(_TOKENS.get(token, token.upper()) for token in name.split("_"))


def _kind(name: str) -> str:
    if name == "qualified":
        return "boolean"
    if name.endswith("_date"):
        return "date"
    if any(token in _NUMERIC_HINTS for token in name.split("_")):
        return "number"
    if name in {"abnormal_desc", "action_taken", "action_result", "impurity_report"}:
        return "textarea"
    if name == "substage":
        return "select"
    return "text"


