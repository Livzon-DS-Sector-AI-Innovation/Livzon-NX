PROCESS_STEP_BY_CODE = {step["code"]: step for step in PROCESS_STEPS}


def process_step(process_code: str) -> dict[str, Any] | None:
    return PROCESS_STEP_BY_CODE.get(process_code)


def validate_process_data(process_code: str, data: dict[str, Any]) -> dict[str, Any]:
    definition = process_step(process_code)
    if not definition:
        raise AppException(message="不支持的工序编码")
    field_by_name = {field["name"]: field for field in definition["fields"]}
    unknown = sorted(set(data) - set(field_by_name))
    if unknown:
        raise AppException(message=f"工序数据包含未知字段：{', '.join(unknown)}")
    cleaned: dict[str, Any] = {}
    for name, value in data.items():
        if value in (None, ""):
            continue
        field = field_by_name[name]
        if field["kind"] == "number":
            try:
                cleaned[name] = float(str(value).replace(",", ""))
            except (TypeError, ValueError) as exc:
                raise AppException(message=f"{field['label']}必须是数字") from exc
        elif field["kind"] == "boolean":
            cleaned[name] = bool(value)
        else:
            cleaned[name] = value
    if not cleaned:
        raise AppException(message="请至少填写一项工序业务数据")
    return cleaned
