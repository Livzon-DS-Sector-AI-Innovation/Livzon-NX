import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'

const task = 'a1000000-0000-0000-0000-000000000001'
test.beforeEach(async ({ page }) => {
  await page.route('**/__dazah_maintenance_status', route => route.fulfill({ json: { phase: 'normal' } }))
  page.on('dialog', dialog => dialog.accept())
})
test('Feishu entry keeps failed values, saves drafts, submits and updates native reports', async ({ context, page }) => {
  await context.addCookies([{ name: 'auth_token', value: `energy-${randomUUID()}`, url: 'http://127.0.0.1:3200' }])
  await page.goto(`/energy/entry?task=${task}&source=feishu`, { waitUntil: 'domcontentloaded' })
  const water = page.getByRole('spinbutton', { name: '101车间水表本次填写' })
  await water.waitFor({ state: 'visible', timeout: 20_000 })
  await expect(water).toBeVisible()
  await expect(water).toHaveValue('')
  await water.fill('999')
  await page.getByRole('button', { name: '提交生效', exact: true }).click()
  await page.getByRole('dialog', { name: '确认能源数据生效' }).getByRole('button', { name: '确 定' }).click()
  await expect(page.getByText('模拟能源服务暂不可用，输入已保留').first()).toBeVisible()
  await expect(water).toHaveValue(/^999(?:\.0+)?$/)
  await page.getByRole('dialog', { name: '确认能源数据生效' }).getByRole('button', { name: '取 消' }).click()
  await water.fill('110')
  await page.getByRole('spinbutton', { name: '101车间电量本次填写' }).fill('50')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.getByText('草稿已保存，正式报表未变更')).toBeVisible()
  await page.getByRole('button', { name: '提交生效', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: '确认能源数据生效' })
  await expect(confirmation).toContainText('本次填写 2 项')
  await expect(confirmation).toContainText('101车间水表（2026-07-02）：— → 110')
  await expect(confirmation).toContainText('101车间电量（2026-07-01）：— → 50')
  await page.getByRole('dialog', { name: '确认能源数据生效' }).getByRole('button', { name: '确 定' }).click()
  await expect(page.getByText('填写已生效，相关报表已更新')).toBeVisible()
  const result = await page.request.get('/api/v1/energy/e2e-state')
  expect((await result.json()).data.source).toBe('feishu')
  await page.goto('/energy/reports?start_date=2026-07-01&end_date=2026-07-01&report_scope=detail', { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('heading', { name: '能源报表', exact: true })).toBeVisible()
  await expect(page.getByText('10 m3', { exact: true })).toBeVisible()
  await expect(page.getByText('50 kWh', { exact: true })).toBeVisible()
  await expect(page.getByText('大罐数量')).toHaveCount(0)
})
